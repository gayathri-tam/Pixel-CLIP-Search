"""CLIP for text query"""

# Prepare text query for CLIP

text_inputs = processor(
    text=[query],
    return_tensors="pt",
    padding=True
)

text_inputs = {
    key: value.to(device)
    for key, value in text_inputs.items()
}

with torch.no_grad():
    text_features = model.get_text_features(**text_inputs)

# Handle Transformers output
if hasattr(text_features, "pooler_output"):
    text_features = text_features.pooler_output

# Normalize
text_features = text_features / text_features.norm(
    p=2,
    dim=-1,
    keepdim=True
)

print("Text embedding created!")
print("Shape:", text_features.shape)

"""Cosine similarity"""

# Calculate similarity between query and all pixel images

text_embedding = text_features.cpu().numpy()[0]

similarities = np.dot(
    old_image_embeddings,
    text_embedding
)

# Get top 5 matching images
top_k = 5

top_indices = np.argsort(similarities)[::-1][:top_k]

print("Top matching images:\n")

for rank, index in enumerate(top_indices, start=1):
    print(
        rank,
        old_valid_image_paths[index],
        "Similarity:",
        round(float(similarities[index]), 4)
    )

