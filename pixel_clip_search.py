"""Generate CLIP embeddings"""

import numpy as np
from PIL import Image
from tqdm import tqdm

old_image_embeddings = []
old_valid_image_paths = []

print("Processing", len(image_paths), "images...")

for image_path in tqdm(image_paths):

    try:
        img = Image.open(image_path).convert("RGB")

        inputs = processor(
            images=img,
            return_tensors="pt"
        )

        inputs = {
            key: value.to(device)
            for key, value in inputs.items()
        }

        with torch.no_grad():
            output = model.get_image_features(**inputs)

        # Handle your Transformers version
        if hasattr(output, "pooler_output"):
            features = output.pooler_output
        else:
            features = output

        # Normalize
        features = features / features.norm(
            p=2,
            dim=-1,
            keepdim=True
        )

        old_image_embeddings.append(
            features.cpu().numpy()[0]
        )

        old_valid_image_paths.append(image_path)

    except Exception as e:
        print("Skipping:", image_path)
        print("Error:", e)

old_image_embeddings = np.array(old_image_embeddings)

print("\nDone!")
print("Embeddings shape:", old_image_embeddings.shape)
print("Valid images:", len(old_valid_image_paths))

"""Enter text query"""

# Enter your search query

query = input("Enter your image search query: ")

